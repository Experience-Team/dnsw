def party(n):
    b = (T[n]['Best for'] or '').lower(); p = []
    if 'solo' in b or 'budget' in b: p.append('solo')
    if 'couple' in b: p.append('couple')
    if 'group' in b or 'pub' in b or 'nightlife' in b: p.append('friends')
    if 'famil' in b: p.append('family')
    return p or ['solo', 'couple', 'friends', 'family']
def getting(n, city):
    g = (T[n]['Getting there'] or '').strip()
    if not g or g.lower().startswith('not stated'): return None
    if city == 'newcastle' and 'Sydney' in g: return None   # written from Sydney: no use from Newcastle
    return g
